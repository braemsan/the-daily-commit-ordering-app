-- Run this in Supabase SQL Editor.

create sequence if not exists public.order_number_seq start 1001;

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null unique,
  price numeric(10,2),
  available boolean not null default true,
  sugar_option boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint not null default nextval('public.order_number_seq'),
  customer_name text not null check (char_length(customer_name) between 1 and 50),
  customer_notes text check (customer_notes is null or char_length(customer_notes) <= 200),
  status text not null default 'new' check (status in ('new','preparing','completed','cancelled')),
  items jsonb not null,
  total numeric(10,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at
before update on public.orders
for each row execute function public.set_updated_at();

