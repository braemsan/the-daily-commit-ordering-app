alter table public.menu_items enable row level security;
alter table public.orders enable row level security;

-- Public customer menu access
create policy "Anyone can read available menu"
on public.menu_items for select
to anon, authenticated
using (available = true);

-- Customers may create orders
create policy "Anyone can create an order"
on public.orders for insert
to anon, authenticated
with check (status = 'new');

-- Booth dashboard can read and update orders.
-- The PIN in this starter app is a convenience lock, not strong server-side security.
create policy "Dashboard can read orders"
on public.orders for select
to anon, authenticated
using (true);

create policy "Dashboard can update order status"
on public.orders for update
to anon, authenticated
using (true)
with check (status in ('new','preparing','completed','cancelled'));

alter publication supabase_realtime add table public.orders;
